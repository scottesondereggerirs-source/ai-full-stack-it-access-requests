class MockProvider:
    """Returns canned extraction responses for reproducible development and tests."""

    def __init__(self) -> None:
        self.responses = MOCK_RESPONSES

    def extract(self, document_id: str, message: str, schema_json: str) -> dict[str, Any]:
        """Return the mock extraction for the given document_id.

        Raises KeyError if no mock response exists for the document.
        """
        if document_id not in self.responses:
            raise KeyError(f"No mock response for document_id={document_id!r}")
        return self.responses[document_id]

    @property
    def response_source(self) -> str:
        return "mock"
